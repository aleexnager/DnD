/* Fotos libres: qué imagen de Wikimedia Commons vale para una criatura.

   Lo comparten la herramienta que preselecciona las fotos
   (tools/fotos-libres.mjs) y la ventana de la foto, que busca más en
   Commons desde el navegador. Solo se aceptan imágenes de dominio público o
   CC0: se pueden usar sin pedir permiso ni citar a nadie, aunque Mesa guarda
   el autor y la licencia de cada una por si se quiere dar el crédito. */

export const COMMONS_API = "https://commons.wikimedia.org/w/api.php";

export const FREE = /^(public domain|pd\b|pdm|cc0|cc-zero|no restrictions|cc-pd)/i;
/* Lo que no es arte de la criatura (rótulos, comercios, disfraces, plantas
   que se llaman igual…) y las imágenes hechas con IA, que no queremos */
export const JUNK = /\b(dall-?e|midjourney|stable diffusion|ai[- ]generated|ai art|generated by ai|logo|flag|coat of arms of|sign|signage|hotel|centre|center|pub|inn|restaurant|shop|store|street|geograph|panoramio|cosplay|costume|comic-?con|fan expo|convention|lego|toy|figurine|t-shirt|poster for|stamp|coin|banknote|map of|diagram|chart|graph|screenshot|game|cards?|tattoo|fruit|plant|flower|cultivar|cactus|aircraft|airplane|helicopter|tank|ship|boat|car|bus|train|rocket|spacex|nasa|band|concert|album|font|icon)\b/i;
/* Pistas de que es una lámina, un grabado o una pintura antigua */
export const ART = /\b(illustration|engraving|woodcut|woodblock|print|ukiyo|etching|lithograph|painting|drawing|plate|tafel|bestiary|manuscript|miniature|codex|watercolou?r|gouache|tapestry|fresco|sketch|art|museum|met|rijksmuseum|lacma|smithsonian|brehm|haeckel|knight|doré|dore|bauer|kittelsen|bilibin|rackham|pyle|hokusai|kuniyoshi|goya|fuseli|blake)\b/i;

const strip = html => String(html || "").replace(/<[^>]*>/g, " ").replace(/&amp;/g, "&").replace(/&quot;/g, "\"")
  .replace(/&#0?39;/g, "'").replace(/&nbsp;/g, " ").replace(/\s+/g, " ").trim();
const noQuery = url => String(url || "").replace(/\?.*$/, "");

/* La búsqueda: imágenes (no vídeos ni PDF) con su miniatura, licencia y autor */
export function commonsURL(query, { limit = 40, width = 640, browser = false } = {}) {
  return COMMONS_API + "?" + new URLSearchParams({
    action: "query", format: "json", generator: "search", gsrnamespace: "6", gsrlimit: String(limit),
    gsrsearch: query + " filetype:bitmap", prop: "imageinfo", iiprop: "url|extmetadata|size|mime",
    iiurlwidth: String(width), iiextmetadatafilter: "LicenseShortName|Artist|Copyrighted",
    ...(browser ? { origin: "*" } : {})
  });
}
export const pagesOf = json => Object.values((json && json.query && json.query.pages) || {}).sort((a, b) => a.index - b.index);

/* Una página de Commons -> candidata, o null si no vale. «rank» es su puesto
   en la búsqueda: lo primero suele ser lo más parecido. */
export function candidateFrom(page, rank = 0) {
  const ii = (page.imageinfo || [])[0];
  if (!ii || !ii.thumburl) return null;
  const meta = ii.extmetadata || {};
  const license = strip((meta.LicenseShortName || {}).value);
  if (!FREE.test(license)) return null;
  if (!/^image\/(jpeg|png|webp|tiff)$/.test(ii.mime || "")) return null;
  const title = String(page.title || "").replace(/^File:/, "");
  const words = title.replace(/[_.-]/g, " ");
  if (JUNK.test(words)) return null;
  const w = ii.width, h = ii.height;
  if (Math.min(w, h) < 280 || w / h > 2.4 || h / w > 2.4) return null;
  let score = 40 - rank * 2;
  if (ART.test(words)) score += 12;
  if (/cc0/i.test(license)) score -= 2;   // el CC0 suele ser foto moderna
  if (w / h > 1.6) score -= 6;            // muy apaisada: la cara queda pequeña
  return {
    file: title, thumb: noQuery(ii.thumburl), page: noQuery(ii.descriptionurl), w, h, license,
    author: strip((meta.Artist || {}).value).slice(0, 90) || "Desconocido", score
  };
}

/* El texto que se guarda con la foto */
export const creditText = c => [c.author || c.a, c.license || c.l, c.page || c.p].filter(Boolean).join(" · ");
